import fs from "node:fs/promises";
import path from "node:path";
import { createClient } from "@sanity/client";

const args = new Set(process.argv.slice(2));
const bestEffort = args.has("--best-effort");

const projectId = process.env.NEXT_PUBLIC_SANITY_PROJECT_ID;
const dataset = process.env.NEXT_PUBLIC_SANITY_DATASET || "production";
const apiVersion = "2021-03-25";

if (!projectId) {
  const message = "Missing NEXT_PUBLIC_SANITY_PROJECT_ID in environment.";
  if (bestEffort) {
    console.warn(`[sync:pull] ${message} Skipping.`);
    process.exit(0);
  }
  console.error(message);
  process.exit(1);
}

const client = createClient({
  projectId,
  dataset,
  apiVersion,
  useCdn: false,
});

const outputPath = path.join(process.cwd(), "data", "content.json");

const run = async () => {
  const [pageInfo, socials, experiences, skills, projects] = await Promise.all([
    client.fetch('*[_type == "pageInfo"][0]'),
    client.fetch('*[_type == "social"]'),
    client.fetch('*[_type == "experience"]{..., technologies[]->}'),
    client.fetch('*[_type == "skill"]'),
    client.fetch('*[_type == "project"]{..., technologies[]->}'),
  ]);

  const payload = {
    meta: {
      source: "sanity-export",
      updatedAt: new Date().toISOString(),
      notes: "Generated by scripts/sync-sanity-to-json.mjs",
    },
    pageInfo: pageInfo || null,
    socials: socials || [],
    experiences: experiences || [],
    skills: skills || [],
    projects: projects || [],
  };

  await fs.writeFile(outputPath, JSON.stringify(payload, null, 2), "utf8");
  console.log(`[sync:pull] Content synced to ${outputPath}`);
};

try {
  await run();
} catch (error) {
  if (bestEffort) {
    console.warn(`[sync:pull] Failed in best-effort mode: ${error?.message || error}`);
    process.exit(0);
  }
  console.error("[sync:pull] Failed:", error);
  process.exit(1);
}
